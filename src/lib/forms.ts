import type { Checklist, Field } from "./types";

/* The medical waste checklists, as checklists. Also written to supabase/migrations/0001_init.sql. */

const created_at = "2026-11-12T00:00:00.000Z";

let n = 0;
const key = (label: string) =>
  label
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "")
    .slice(0, 36) || `f${++n}`;

const head = (label_en: string, label_ar = ""): Field => ({ key: `h_${key(label_en)}`, label_en, label_ar, type: "heading", required: false });
const item = (label_en: string, label_ar = "", extra: Partial<Field> = {}): Field => ({
  key: key(label_en),
  label_en,
  label_ar,
  type: "check",
  required: true,
  ...extra,
});
const num = (label_en: string, label_ar: string, unit = "", min: number | null = null, max: number | null = null, required = true): Field => ({
  key: key(label_en),
  label_en,
  label_ar,
  type: "number",
  unit,
  min,
  max,
  required,
});
const text = (label_en: string, label_ar: string, required = true): Field => ({ key: key(label_en), label_en, label_ar, type: "text", required });
const yesno = (label_en: string, label_ar: string, extra: Partial<Field> = {}): Field => ({ key: key(label_en), label_en, label_ar, type: "yesno", required: true, ...extra });
const select = (label_en: string, label_ar: string, options: string[], required = true): Field => ({ key: key(label_en), label_en, label_ar, type: "select", options, required });

const base = (o: Partial<Checklist> & Pick<Checklist, "id" | "title_en" | "title_ar" | "icon" | "color" | "fields" | "sort">): Checklist => ({
  department_id: "dep-waste",
  range_note: "",
  footer_note: "Infection Prevention and Control Department · Environmental Services",
  orientation: "landscape",
  active: true,
  created_at,
  ...o,
});

